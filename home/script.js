const languageButtons = document.querySelectorAll(".lang-button");
const translatableElements = document.querySelectorAll("[data-i18n]");

function applyLanguage(lang) {
  const dictionary = translations[lang] || translations.en;

  document.documentElement.lang = lang === "pt-BR" ? "pt-BR" : "en";
  document.title = dictionary.pageTitle;

  translatableElements.forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  languageButtons.forEach((button) => {
    const active = button.dataset.lang === lang;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  localStorage.setItem("linuxtoys-dev-lang", lang);
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

function getInitialLanguage() {
  const savedLanguage = localStorage.getItem("linuxtoys-dev-lang");

  if (savedLanguage === "en" || savedLanguage === "pt-BR") {
    return savedLanguage;
  }

  const browserLanguages = navigator.languages?.length
    ? navigator.languages
    : [navigator.language];

  const prefersPortuguese = browserLanguages.some(
    (language) => language?.toLowerCase().startsWith("pt")
  );

  return prefersPortuguese ? "pt-BR" : "en";
}

applyLanguage(getInitialLanguage());
